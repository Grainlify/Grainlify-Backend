func TestFindDuplicates_MarksSameAuthorPairsDistinctly(t *testing.T) {
	d := addedPatch("func Same() {}", "// identical body", "var x = 1")
	pairs := FindDuplicates([]DuplicateCandidate{
		{VerdictID: "v1", Login: "alice", Diff: d},
		{VerdictID: "v2", Login: "Alice", Diff: d},
	}, 0.5, nil)
	if len(pairs) != 1 {
		t.Fatalf("got %d pairs, want 1", len(pairs))
	}
	// One person splitting work across PRs is a different problem from a
	// farm, and a reviewer has to be able to tell them apart.
	if !pairs[0].SameAuthor {
		t.Error("SameAuthor = false for the same login in different case")
	}
}

func TestLexicalSimilarity_IdenticalAndDisjoint(t *testing.T) {
	d := addedPatch("alpha beta gamma delta epsilon zeta", "eta theta iota kappa")
	if got := LexicalSimilarity(d, d); got != 1 {
		t.Errorf("identical diffs scored %v, want 1", got)
	}
	if got := LexicalSimilarity(d, addedPatch("completely different words here entirely", "nothing shared at all")); got != 0 {
		t.Errorf("disjoint diffs scored %v, want 0", got)
	}
	if got := LexicalSimilarity("", d); got != 0 {
		t.Errorf("empty diff scored %v, want 0", got)
	}
}

// --- §5.8 payout ---

func specPayoutConfig() map[string]string {
	return map[string]string{
		"units_rejected": "0", "units_accepted": "1", "units_substantial": "3", "units_exceptional": "5",
		"payout_floor": "50", "payout_floor_strategy": "fund_highest_buckets_first",
	}
}

// TestComputePayout_SpecWorkedExample reproduces §5.8's own table exactly:
// 40 accepted, 12 substantial, 3 exceptional, $10,000 pool -> 91 units,
// unit value $109.89, so accepted $110 / substantial $330 / exceptional $549.
func TestComputePayout_SpecWorkedExample(t *testing.T) {
	var prs []JudgedPR
	add := func(n int, bucket string) {
		for i := 0; i < n; i++ {
			prs = append(prs, JudgedPR{VerdictID: fmt.Sprintf("%s-%d", bucket, i), Login: fmt.Sprintf("u%s%d", bucket[:1], i), Bucket: bucket})
		}
	}
	add(40, "accepted")
	add(12, "substantial")
	add(3, "exceptional")

	plan, err := ComputePayout(prs, 10000, specPayoutConfig())
	if err != nil {
		t.Fatalf("ComputePayout: %v", err)
	}
	if plan.TotalUnits != 91 {
		t.Errorf("TotalUnits = %d, want 91", plan.TotalUnits)
	}
	if got := round2(plan.UnitValue); got != 109.89 {
		t.Errorf("UnitValue = %v, want 109.89", got)
	}
	if plan.FloorApplied {
		t.Error("floor applied when the unit value was comfortably above it")
	}

	amounts := map[string]float64{}
	for _, e := range plan.Entries {
		amounts[e.Bucket] = e.Amount
		if !e.Funded {
			t.Errorf("%s entry unfunded with an adequate pool", e.Bucket)
		}
	}
	// The spec's rounded figures.
	if amounts["accepted"] != 109.89 || amounts["substantial"] != 329.67 || amounts["exceptional"] != 549.45 {
		t.Errorf("per-bucket amounts = %+v, want ~110/330/549", amounts)
	}
}

func TestComputePayout_RejectedTakeNoShare(t *testing.T) {
	plan, err := ComputePayout([]JudgedPR{
		{VerdictID: "a", Login: "alice", Bucket: "accepted"},
		{VerdictID: "r", Login: "mallory", Bucket: "rejected"},
	}, 100, specPayoutConfig())
	if err != nil {
		t.Fatalf("ComputePayout: %v", err)
	}
	if plan.TotalUnits != 1 {
		t.Errorf("TotalUnits = %d, want 1 - a rejected PR contributes no units", plan.TotalUnits)
	}
	for _, e := range plan.Entries {
		if e.Bucket == "rejected" && (e.Amount != 0 || e.Funded) {
			t.Errorf("rejected entry was paid %v (funded=%v)", e.Amount, e.Funded)
		}
	}
}

// The floor is the part that generates bad press if it's wrong: nobody
// should be silently paid a token amount for real work.
func TestComputePayout_FloorFundsHighestBucketsFirst(t *testing.T) {
	var prs []JudgedPR
	prs = append(prs, JudgedPR{VerdictID: "e1", Login: "exceptional-one", Bucket: "exceptional"})
	prs = append(prs, JudgedPR{VerdictID: "s1", Login: "substantial-one", Bucket: "substantial"})
	for i := 0; i < 20; i++ {
		prs = append(prs, JudgedPR{VerdictID: fmt.Sprintf("a%d", i), Login: fmt.Sprintf("accepted-%02d", i), Bucket: "accepted"})
	}

	// 5 + 3 + 20 = 28 units. A $500 pool gives $17.86/unit, well under the
	// $50 floor, so the floor strategy has to kick in.
	plan, err := ComputePayout(prs, 500, specPayoutConfig())
	if err != nil {
		t.Fatalf("ComputePayout: %v", err)
	}
	if !plan.FloorApplied {
		t.Fatal("floor not applied despite a unit value below it")
	}
	if plan.UnitValue != 50 {
		t.Errorf("UnitValue = %v, want the floor of 50", plan.UnitValue)
	}

	byID := map[string]PayoutEntry{}
	total := 0.0
	for _, e := range plan.Entries {
		byID[e.VerdictID] = e
		total += e.Amount
	}
	// Highest buckets first: exceptional (5 x 50 = 250) and substantial
	// (3 x 50 = 150) are funded before any accepted entry.
	if !byID["e1"].Funded || byID["e1"].Amount != 250 {
		t.Errorf("exceptional entry = %+v, want funded at 250", byID["e1"])
	}
	if !byID["s1"].Funded || byID["s1"].Amount != 150 {
		t.Errorf("substantial entry = %+v, want funded at 150", byID["s1"])
	}
	// 500 - 250 - 150 = 100 left, so exactly 2 accepted entries at 50.
	funded := 0
	for _, e := range plan.Entries {
		if e.Bucket == "accepted" && e.Funded {
			funded++
			if e.Amount != 50 {
				t.Errorf("accepted entry paid %v, want the floor of 50", e.Amount)
			}
		}
	}
	if funded != 2 {
		t.Errorf("funded accepted entries = %d, want 2", funded)
	}
	if plan.UnfundedCount != 18 {
		t.Errorf("UnfundedCount = %d, want 18", plan.UnfundedCount)
	}
	if total > 500.0001 {
		t.Errorf("paid out %v, which exceeds the %v pool", total, 500.0)
	}
	if plan.Note == "" {
		t.Error("no note explaining why the floor was applied - this is the rule that has to be explainable")
	}
}


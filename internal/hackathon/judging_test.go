func boolPtr(b bool) *bool { return &b }

func addedPatch(lines ...string) string {
	var b strings.Builder
	b.WriteString("--- a/f\n+++ b/f\n")
	for _, l := range lines {
		b.WriteString("+" + l + "\n")
	}
	return b.String()
}

// --- §5.3 diff_stats: computed in code, never estimated by the model ---

func TestComputeDiffStats_ExcludesLockfileGeneratedAndWhitespace(t *testing.T) {
	files := []FileChange{
		{Filename: "src/auth/login.go", Patch: addedPatch("func Login() {", "  return nil", "}")},
		{Filename: "package-lock.json", Patch: addedPatch(strings.Repeat("dep", 1), "more", "lines")},
		{Filename: "api/gen.pb.go", Patch: "--- a/f\n+++ b/f\n+// Code generated by protoc. DO NOT EDIT.\n+type X struct{}\n"},
		{Filename: "src/style.css", Patch: addedPatch("", "   ", "")},
	}
	s := ComputeDiffStats(files)

	if s.FilesChanged != 4 {
		t.Errorf("FilesChanged = %d, want 4", s.FilesChanged)
	}
	if s.LockfileLines != 3 {
		t.Errorf("LockfileLines = %d, want 3", s.LockfileLines)
	}
	if s.GeneratedLines != 2 {
		t.Errorf("GeneratedLines = %d, want 2 (the generated banner counts the whole file)", s.GeneratedLines)
	}
	// Only the 3 real Go lines count: lockfile, generated and whitespace-only
	// additions are all excluded. This is the number that stops a PR
	// misrepresenting its own size.
	if s.MeaningfulLines != 3 {
		t.Errorf("MeaningfulLines = %d, want 3", s.MeaningfulLines)
	}
	if !s.TouchesCorePath {
		t.Error("TouchesCorePath = false despite a change under src/")
	}
}

func TestComputeDiffStats_DetectsTestsAndDocsOnly(t *testing.T) {
	withTests := ComputeDiffStats([]FileChange{
		{Filename: "internal/api/handler.go", Patch: addedPatch("x := 1")},
		{Filename: "internal/api/handler_test.go", Patch: addedPatch("func TestX(t *testing.T) {}")},
	})
	if !withTests.TestsAdded || withTests.TestLines == 0 {
		t.Errorf("TestsAdded=%v TestLines=%d, want tests detected", withTests.TestsAdded, withTests.TestLines)
	}
	if withTests.DocsOnly {
		t.Error("DocsOnly = true for a change that includes code")
	}

	docsOnly := ComputeDiffStats([]FileChange{
		{Filename: "README.md", Patch: addedPatch("Some prose.")},
		{Filename: "docs/guide.md", Patch: addedPatch("More prose.")},
	})
	if !docsOnly.DocsOnly {
		t.Error("DocsOnly = false for a docs-only change")
	}
}

func TestComputeDiffStats_FallsBackToGitHubCountsWithoutAPatch(t *testing.T) {
	// GitHub omits the patch for binary files and very large diffs; the
	// change is still real and must not read as zero.
	s := ComputeDiffStats([]FileChange{{Filename: "src/img.png", Additions: 40, Deletions: 5}})
	if s.LinesAdded != 40 || s.LinesRemoved != 5 {
		t.Errorf("got +%d/-%d, want +40/-5", s.LinesAdded, s.LinesRemoved)
	}
}

// --- §5.1 pre-filter ---

func TestPrefilter_Section51(t *testing.T) {
	good := PrefilterInput{
		Stats:                       DiffStats{MeaningfulLines: 30},
		CIPassed:                    boolPtr(true),
		LinkedToGrainHackIssue:      true,
		AuthorIsAssignedContributor: true,
	}

	if res := Prefilter(good); res.Rejected {
		t.Fatalf("a clean PR was rejected: %s", res.Reason)
	}

	tests := []struct {
		name   string
		mutate func(*PrefilterInput)
		want   string
	}{
		{"unassigned author", func(in *PrefilterInput) { in.AuthorIsAssignedContributor = false }, "not the contributor assigned"},
		{"no linked issue", func(in *PrefilterInput) { in.LinkedToGrainHackIssue = false }, "not linked to a GrainHack issue"},
		{"issue author", func(in *PrefilterInput) { in.AuthorIsIssueAuthor = true }, "opened the issue"},
		{"repo admin", func(in *PrefilterInput) { in.AuthorIsRepoAdmin = true }, "admin of the repository"},
		{"failing CI", func(in *PrefilterInput) { in.CIPassed = boolPtr(false) }, "CI was failing"},
		{"docs only", func(in *PrefilterInput) { in.Stats.DocsOnly = true }, "documentation only"},
		{"no meaningful lines", func(in *PrefilterInput) { in.Stats.MeaningfulLines = 0 }, "no meaningful code changes"},
		{"below the minimum size", func(in *PrefilterInput) {
			in.Stats.MeaningfulLines = 3
			in.MinMeaningfulLines = 10
		}, "below this event's minimum"},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			in := good
			tc.mutate(&in)
			res := Prefilter(in)
			if !res.Rejected {
				t.Fatalf("expected rejection")
			}
			if !strings.Contains(res.Reason, tc.want) {
				t.Errorf("reason = %q, want it to mention %q", res.Reason, tc.want)
			}
		})
	}
}


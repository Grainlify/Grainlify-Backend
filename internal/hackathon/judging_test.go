// --- §5.2 duplicate detection ---

func TestFindDuplicates_FlagsNearIdenticalAcrossAccounts(t *testing.T) {
	body := addedPatch(
		"func retryWithBackoff(ctx context.Context, attempts int) error {",
		"  for i := 0; i < attempts; i++ {",
		"    if err := do(ctx); err == nil { return nil }",
		"    time.Sleep(backoff(i))",
		"  }",
		"  return ErrExhausted",
		"}",
	)
	// Same code, different indentation and a renamed variable - the shape a
	// copied submission actually takes.
	copied := strings.ReplaceAll(strings.ReplaceAll(body, "  ", " "), "attempts", "tries")
	unrelated := addedPatch("const Theme = 'dark'", "export default Theme")

	pairs := FindDuplicates([]DuplicateCandidate{
		{VerdictID: "v1", Login: "alice", Diff: body},
		{VerdictID: "v2", Login: "bob", Diff: copied},
		{VerdictID: "v3", Login: "carol", Diff: unrelated},
	}, 0.5, nil)

	if len(pairs) != 1 {
		t.Fatalf("got %d flagged pairs, want 1: %+v", len(pairs), pairs)
	}
	if pairs[0].EarlierVerdictID != "v1" || pairs[0].LaterVerdictID != "v2" {
		t.Errorf("flagged %s/%s, want v1/v2 with the later one flagged", pairs[0].EarlierVerdictID, pairs[0].LaterVerdictID)
	}
	if pairs[0].SameAuthor {
		t.Error("SameAuthor = true for two different accounts - cross-account duplication is the farming case")
	}
}

